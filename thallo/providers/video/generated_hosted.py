"""Hosted generative video. Off by default (THALLO_ALLOW_GENERATED_MEDIA=1 to enable).

Shape followed: OpenAI's video API as documented in Nov 2026 (not verified against a live call):
    POST {base}/videos              {"model", "prompt", "seconds", "size": "WxH"} -> {"id", "status"}
    GET  {base}/videos/{id}         -> {"status": "queued"|"in_progress"|"completed"|"failed"}
    GET  {base}/videos/{id}/content -> MP4 bytes
Serves only `action="generate"`. Every file is GENERATED, labelled at ingest and FLAGged. Without a
verified likeness consent the prompt forbids people, products, premises and text.

Operator configuration, in the environment only:
    THALLO_VIDEO_GEN_ORIGINS        https origins allowed
    THALLO_VIDEO_GEN_ORIGINS_BASE   the base URL including /v1
    THALLO_BRAND_ROOT               where the tenant's output folder is
Tenant settings: `usd_per_unit` is per second of video.
"""
from __future__ import annotations

import json
import re
import time
from collections.abc import Callable, Mapping
from decimal import Decimal
from pathlib import Path
from typing import Any

from thallo.connections.registry import ProviderContext, ProviderRegistry
from thallo.contracts import connection as c
from thallo.contracts.enums import Capability, ConnectionMode, MediaKind, MediaProvenance
from thallo.providers.image.http_media import (
    ConsentLookup,
    HttpMediaProvider,
    MediaCall,
    MediaProviderError,
    MediaSettings,
    MediaTransportFn,
    check_reply,
    guarded_prompt,
)
from thallo.providers.text.base import Auth

NAME = "generated_hosted"
_ID = re.compile(r"^[A-Za-z0-9_-]{1,100}$")
MAX_POLLS = 120
DEFAULT_SECONDS = 8


class HostedVideoGenerator(HttpMediaProvider):
    capability = Capability.VIDEO
    name = NAME
    mode = ConnectionMode.HOSTED
    origins_env = "THALLO_VIDEO_GEN_ORIGINS"
    licence_note = "generated by the vendor's model under its terms; carries a disclosure label"

    def __init__(self, ctx: ProviderContext, *, transport: MediaTransportFn | None = None,
                 environ: Mapping[str, str] | None = None, consents: ConsentLookup | None = None,
                 sleep: Callable[[float], None] = time.sleep) -> None:
        super().__init__(ctx, transport=transport, environ=environ, consents=consents)
        self.sleep = sleep

    def serves(self, request: c.Request) -> str | None:
        assert isinstance(request, c.VideoRequest)
        if request.action != "generate":
            return "generated video only serves action generate"
        if not request.script or not request.script.strip():
            return "a generated clip needs a script"
        return None

    def _seconds(self, request: c.VideoRequest) -> int:
        return max(1, round((request.duration_ms or DEFAULT_SECONDS * 1000) / 1000))

    def units(self, request: c.Request) -> Decimal:
        assert isinstance(request, c.VideoRequest)
        return Decimal(self._seconds(request))

    def produce(self, request: c.Request, auth: Auth | None) -> tuple[bytes, str, str, dict[str, Any], Decimal]:
        assert isinstance(request, c.VideoRequest) and self.settings is not None and request.script
        base, t = self.base_url(), self.settings.timeout_s
        people = self.people_allowed(request)
        prompt = guarded_prompt(request.script, people)
        body = json.dumps({"model": self.model, "prompt": prompt, "seconds": str(self._seconds(request)),
                           "size": f"{request.width}x{request.height}"}).encode()
        reply = self._send(MediaCall("POST", f"{base}/videos", {"content-type": "application/json"}, body, auth, t))
        check_reply(reply, NAME)
        vid = reply.body.get("id") if isinstance(reply.body, dict) else None
        if not isinstance(vid, str) or not _ID.match(vid):
            raise MediaProviderError("generated video returned an unexpected response shape (id)")
        for _ in range(MAX_POLLS):
            r = self._send(MediaCall("GET", f"{base}/videos/{vid}", {}, None, auth, t))
            check_reply(r, NAME)
            status = r.body.get("status") if isinstance(r.body, dict) else None
            if status == "completed":
                break
            if status not in ("queued", "in_progress"):
                raise MediaProviderError("the vendor did not finish the clip")
            self.sleep(5.0)
        else:
            raise MediaProviderError("the clip took too long")
        content = self._send(MediaCall("GET", f"{base}/videos/{vid}/content", {}, None, auth, t))
        check_reply(content, NAME)
        if content.raw[4:8] != b"ftyp":
            raise MediaProviderError("the vendor returned bytes that are not an MP4")
        settings = {"external_id": vid, "prompt_sent": prompt, "people_allowed": people,
                    "seconds": self._seconds(request)}
        return content.raw, "video/mp4", "mp4", settings, Decimal(self._seconds(request))

    def media_result(self, request: c.Request, sha: str, mime: str, path: Path) -> c.MediaResult:
        assert isinstance(request, c.VideoRequest)
        return c.MediaResult(kind=MediaKind.VIDEO, sha256=sha, mime=mime, storage_uri=path.as_uri(),
                             provenance=MediaProvenance.GENERATED, width=request.width, height=request.height,
                             duration_ms=self._seconds(request) * 1000, disclosure_required=True)


def create(ctx: ProviderContext, transport: MediaTransportFn | None = None,
           environ: Mapping[str, str] | None = None, consents: ConsentLookup | None = None) -> HostedVideoGenerator:
    return HostedVideoGenerator(ctx, transport=transport, environ=environ, consents=consents)


def register(registry: ProviderRegistry) -> None:
    registry.register(Capability.VIDEO, NAME, ConnectionMode.HOSTED, create, settings_schema=MediaSettings)
